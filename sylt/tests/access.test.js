import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtemp} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {GraffitiRepository} from '../src/repository.js';
const require=createRequire(import.meta.url);
const {GraffitiLocal}=require('@graffiti-garden/implementation-local');
test('private recording, friend snapshot, public copy and deletion enforce access independently',async()=>{
 const folder=await mkdtemp(path.join(os.tmpdir(),'encore-test-'));
 const api=new GraffitiLocal({pouchDBOptions:{name:path.join(folder,'records')}});
 const alice=new GraffitiRepository({actor:'did:example:alice'},api),bob=new GraffitiRepository({actor:'did:example:bob'},api),stranger=new GraffitiRepository({actor:'did:example:stranger'},api);
 const blob=new Blob(['sample audio bytes'],{type:'audio/wav'});
 const privateMedia=await alice.upload(blob);
 const entry=await alice.post('practice',{media:privateMedia,title:'Private practice',mediaType:'audio/wav',duration:1});
 assert.deepEqual(entry.allowed,['did:example:alice']);
 await assert.rejects(()=>bob.get(entry.url));
 await assert.rejects(()=>bob.media(privateMedia));
 assert.equal((await bob.list()).some(o=>o.url===entry.url),false);
 assert.equal(await (await alice.media(privateMedia)).text(),'sample audio bytes');
 const sharedMedia=await alice.upload(blob,['did:example:alice','did:example:bob']);
 const shared=await alice.post('shared',{media:sharedMedia,title:'Shared practice',mediaType:'audio/wav',duration:1,source:entry.url,audience:['did:example:alice','did:example:bob']},['did:example:alice','did:example:bob']);
 assert.equal((await bob.get(shared.url)).actor,'did:example:alice');
 assert.equal((await bob.media(sharedMedia)).type,'audio/wav');
 await assert.rejects(()=>stranger.get(shared.url));
 await assert.rejects(()=>stranger.media(sharedMedia));
 await assert.rejects(()=>bob.remove(shared.url));
 const publicMedia=await alice.upload(blob,null);
 const publicPost=await alice.post('public',{media:publicMedia,title:'Public take',mediaType:'audio/wav',duration:1},null);
 assert.equal((await api.get(publicPost.url,{})).value.title,'Public take');
 assert.equal((await api.getMedia(publicMedia,{})).data.size,blob.size);
 await assert.rejects(()=>api.get(entry.url,{}));
 await assert.rejects(()=>api.getMedia(privateMedia,{}));
 const comment=await bob.post('comment',{post:shared.url,text:'Keep going!'},['did:example:alice','did:example:bob']);
 await assert.rejects(()=>api.get(comment.url,{}));
 await alice.remove(publicPost.url);await alice.removeMedia(publicMedia);
 await assert.rejects(()=>api.get(publicPost.url,{}));await assert.rejects(()=>api.getMedia(publicMedia,{}));
 assert.equal((await alice.get(entry.url)).url,entry.url);
});
